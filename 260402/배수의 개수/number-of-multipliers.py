# 1. 각각의 개수를 저장할 변수 두 개 준비
cnt3 = 0
cnt5 = 0

# 2. 10번 반복해서 숫자를 하나씩 입력받기
for _ in range(10):
    num = int(input())
    
    # 3. 3의 배수인지 확인 (독립된 if)
    if num % 3 == 0:
        cnt3 += 1  # 3의 배수가 몇 개인지 센다
        
    # 4. 5의 배수인지 확인 (독립된 if)
    if num % 5 == 0: 
        cnt5 += 1  # 5의 배수가 몇 개인지 센다

# 5. 마지막에 공백을 두고 두 결과 출력
print(cnt3, cnt5)